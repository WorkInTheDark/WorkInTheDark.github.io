#!/usr/bin/env python3
"""Import event pictures for the PhD Simulator.

Drop images named <category>-<n>.<png|jpg|jpeg|webp|heic> (for example research-1.png) into
tools/phd-sim/art-inbox/ and run:

    python3 tools/phd-sim/import-art.py

Each image is center-cropped to portrait 2:3, resized to 360 x 540 px and saved as
assets/phd-sim/art/<category>-<n>.jpg (replacing an older .svg for the same slot). The original
moves to art-inbox/done/. Then assets/js/phd-sim/ui/art-manifest.js is rewritten to list every
picture per category, so the game uses whatever exists. Prompts: docs/phd-simulator/art-prompts.md.
Uses macOS `sips`; no other dependencies.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
INBOX = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "tools", "phd-sim", "art-inbox")
ART = os.path.join(ROOT, "assets", "phd-sim", "art")
MANIFEST = os.path.join(ROOT, "assets", "js", "phd-sim", "ui", "art-manifest.js")
CATEGORIES = ["research", "data", "writing", "reviews", "advisor", "lab", "milestone", "teaching",
              "career", "travel", "world", "life", "wellbeing", "exit"]
W, H = 360, 540   # portrait 2:3: the picture fills a column on the left of the event card
NAME = re.compile(r"^(" + "|".join(CATEGORIES) + r")-(\d+)\.(png|jpe?g|webp|heic)$", re.I)


def sips(*args):
    return subprocess.run(["sips", *args], check=True, capture_output=True, text=True).stdout


def dims(path):
    out = sips("-g", "pixelWidth", "-g", "pixelHeight", path)
    w = int(re.search(r"pixelWidth: (\d+)", out).group(1))
    h = int(re.search(r"pixelHeight: (\d+)", out).group(1))
    return w, h


def import_one(src, cat, n):
    dst = os.path.join(ART, "%s-%d.jpg" % (cat, n))
    tmp = dst + ".tmp.png"
    shutil.copyfile(src, tmp)
    w, h = dims(tmp)
    if w * H > h * W:      # too wide: keep the full height, trim the sides
        cw, ch = h * W // H, h
    else:                  # too tall: keep the full width, trim top and bottom
        cw, ch = w, w * H // W
    if (cw, ch) != (w, h):
        sips("-c", str(ch), str(cw), tmp)
    sips("-z", str(H), str(W), tmp)
    sips("-s", "format", "jpeg", "-s", "formatOptions", "82", tmp, "--out", dst)
    os.remove(tmp)
    old = os.path.join(ART, "%s-%d.svg" % (cat, n))
    if os.path.exists(old):
        os.remove(old)
    return dst


def write_manifest():
    files = {}
    for f in sorted(os.listdir(ART)):
        m = re.match(r"^([a-z]+)-(\d+)\.(jpg|svg)$", f)
        if not m or m.group(1) not in CATEGORIES:
            continue
        slot = (m.group(1), int(m.group(2)))
        # A photo-like .jpg wins over the older .svg for the same slot.
        if slot in files and files[slot].endswith(".jpg"):
            continue
        files[slot] = f
    by_cat = {c: [files[s] for s in sorted(files) if s[0] == c] for c in CATEGORIES}
    lines = ["// The event pictures that exist, per category (2026-10-17 on). Generated by",
             "// tools/phd-sim/import-art.py; don't edit by hand. Files live in assets/phd-sim/art/.",
             "export const ART_FILES = {"]
    for c in CATEGORIES:
        lines.append("  %s: [%s]," % (c, ", ".join('"%s"' % f for f in by_cat[c])))
    lines.append("};")
    with open(MANIFEST, "w") as fh:
        fh.write("\n".join(lines) + "\n")
    return by_cat


def main():
    done = os.path.join(INBOX, "done")
    imported = []
    if os.path.isdir(INBOX):
        for f in sorted(os.listdir(INBOX)):
            m = NAME.match(f)
            src = os.path.join(INBOX, f)
            if not os.path.isfile(src):
                continue
            if not m:
                print("skipped (name should be <category>-<n>.png, categories: %s): %s" % (", ".join(CATEGORIES), f))
                continue
            dst = import_one(src, m.group(1).lower(), int(m.group(2)))
            os.makedirs(done, exist_ok=True)
            shutil.move(src, os.path.join(done, f))
            imported.append(os.path.relpath(dst, ROOT))
    by_cat = write_manifest()
    for p in imported:
        print("imported", p, "(%d KB)" % (os.path.getsize(os.path.join(ROOT, p)) // 1024))
    missing = [c for c in CATEGORIES if not by_cat[c]]
    print("%d imported. Pictures per category: %s" % (len(imported), ", ".join("%s %d" % (c, len(by_cat[c])) for c in CATEGORIES)))
    if missing:
        print("No pictures yet for: " + ", ".join(missing))


if __name__ == "__main__":
    main()
